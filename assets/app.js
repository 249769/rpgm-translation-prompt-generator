  async function collectEntryFiles(entry, prefix) {
    const currentPath = normalizePath(prefix ? `${prefix}${entry.name}` : entry.name);
    if (entry.isFile) {
      return await new Promise((resolve) => {
        entry.file((file) => {
          file.relativePath = currentPath;
          resolve([file]);
        }, () => resolve([]));
      });
    }
    if (!entry.isDirectory) return [];
    const reader = entry.createReader();
    const all = [];
    while (true) {
      const entries = await new Promise((resolve) => reader.readEntries(resolve));
      if (!entries.length) break;
      for (const child of entries) {
        all.push(...await collectEntryFiles(child, `${currentPath}/`));
      }
    }
    return all;
  }

  async function collectHandleFiles(handle, prefix) {
    const currentPath = normalizePath(prefix ? `${prefix}${handle.name}` : handle.name);
    if (handle.kind === "file") {
      const file = await handle.getFile();
      file.relativePath = currentPath;
      return [file];
    }
    if (handle.kind !== "directory") return [];
    const all = [];
    for await (const child of handle.values()) {
      all.push(...await collectHandleFiles(child, `${currentPath}/`));
    }
    return all;
  }

  async function filesFromDataTransfer(dataTransfer) {
    const files = [];
    const seen = new Set();
    const addFile = (file) => {
      if (!file) return;
      const key = fileKey(file);
      if (seen.has(key)) return;
      seen.add(key);
      files.push(file);
    };
    const items = Array.from(dataTransfer.items || []);
    for (const item of items) {
      if (item.getAsFileSystemHandle) {
        try {
          const handle = await item.getAsFileSystemHandle();
          if (handle) {
            const collected = await collectHandleFiles(handle, "");
            collected.forEach(addFile);
          }
          continue;
        } catch (_) {
          // Fall back to webkitGetAsEntry or files below.
        }
      }
      const entry = item.webkitGetAsEntry ? item.webkitGetAsEntry() : null;
      if (entry) {
        const collected = await collectEntryFiles(entry, "");
        collected.forEach(addFile);
        continue;
      }
      const file = item.getAsFile ? item.getAsFile() : null;
      if (file) addFile(file);
    }
    for (const file of Array.from(dataTransfer.files || [])) addFile(file);
    return files;
  }

